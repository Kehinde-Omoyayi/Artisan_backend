"""The service catalogue: categories and the sub-services customers actually ask for.

WHY THIS FILE EXISTS SEPARATELY
The list is data, not code. Keeping it out of the model and out of the seeder means
it can be reviewed, diffed and re-ranked without touching anything that runs.

HOW IT WAS BUILT
See docs/SERVICE_TAXONOMY_RESEARCH.md for the method and sources. In short, a
category is "core" when it appears as a top-level category on most Nigerian
artisan marketplaces AND the trade is a recognised Nigerian construction/household
trade. Tiers are a launch order, not a quality ranking.

FIELDS
    name      ServiceCategory.name (primary key, so keep it stable once shipped)
    tier      "core" | "growth" | "specialist" - the seeding order
    why       one line, for the research document only
    services  (name, description) pairs -> Service.name / Service.description

Service.name is globally unique in the schema, so names are written the way a
customer would search for them ("AC Servicing & Gas Refill", not "Servicing").
Descriptions are customer-facing: what the job is, not what it costs. Pricing is
the artisan's `starting_price`, never a catalogue fact.
"""

