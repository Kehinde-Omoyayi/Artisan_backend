def iter_services():
    """Yield (category_name, service_name, description, tier) for every row."""
    for category in CATEGORIES:
        for name, description in category["services"]:
            yield category["name"], name, description, category["tier"]


def summary():
    """Counts for the research document and the loader's dry run."""
    tiers = {}
    for category in CATEGORIES:
        tiers.setdefault(category["tier"], {"categories": 0, "services": 0})
        tiers[category["tier"]]["categories"] += 1
        tiers[category["tier"]]["services"] += len(category["services"])
    return {
        "categories": len(CATEGORIES),
        "services": sum(len(c["services"]) for c in CATEGORIES),
        "tiers": tiers,
    }
